describe('deriveSessionRecord — additional synthetic cases', () => {
  const baseContext = {
    sessionId: 'synthetic-session',
    parentSessionId: null,
    agentType: null,
    collectedBy: 'stop' as const,
    endedAt: null,
    exitReason: 'turn_stop' as const,
    sessionEndReason: null,
    pushedAt: null,
    sawRemoteEnv: false,
    repoRootHint: '/repo',
    nowIso: '2026-08-25T09:00:00.000Z',
  };

  function assistantRow(opts: {
    requestId: string;
    model: string;
    output: number;
    gitBranch: string;
    content: unknown[];
  }) {
    return {
      type: 'assistant',
      requestId: opts.requestId,
      timestamp: '2026-08-25T09:00:00.000Z',
      gitBranch: opts.gitBranch,
      cwd: '/repo',
      entrypoint: 'claude-vscode',
      version: '2.1.229',
      effort: 'high',
      message: {
        model: opts.model,
        content: opts.content,
        usage: {
          input_tokens: 1,
          output_tokens: opts.output,
          cache_creation_input_tokens: 0,
          cache_read_input_tokens: 0,
        },
      },
    };
  }

  it('deduplicates branches_seen while keeping first-seen order, distinguishing branch_start from branch_end', () => {
    const rows = [
      assistantRow({ requestId: 'r1', model: 'claude-sonnet-5', output: 10, gitBranch: 'main', content: [] }),
      assistantRow({ requestId: 'r2', model: 'claude-sonnet-5', output: 10, gitBranch: 'feat/x', content: [] }),
      assistantRow({ requestId: 'r3', model: 'claude-sonnet-5', output: 10, gitBranch: 'main', content: [] }),
    ];
    const record = deriveSessionRecord(rows, baseContext);
    expect(record.branch_start).toBe('main');
    expect(record.branch_end).toBe('main');
    expect(record.branches_seen).toEqual(['main', 'feat/x']);
  });

  it('picks model_primary as the model with the most output_tokens, not the first one seen', () => {
    const rows = [
      assistantRow({ requestId: 'r1', model: 'claude-haiku-5', output: 5, gitBranch: 'main', content: [] }),
      assistantRow({ requestId: 'r2', model: 'claude-sonnet-5', output: 500, gitBranch: 'main', content: [] }),
    ];
    const record = deriveSessionRecord(rows, baseContext);
    expect(record.models_seen).toEqual(['claude-haiku-5', 'claude-sonnet-5']);
    expect(record.model_primary).toBe('claude-sonnet-5');
  });

  it('counts tool_calls_interrupted from toolUseResult.interrupted === true on a tool_result echo', () => {
    const rows = [
      {
        type: 'user',
        timestamp: '2026-08-25T09:00:00.000Z',
        gitBranch: 'main',
        cwd: '/repo',
        message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 't1', content: 'x' }] },
        toolUseResult: { interrupted: true, stdout: '', stderr: '', isImage: false, noOutputExpected: false },
      },
      {
        type: 'user',
        timestamp: '2026-08-25T09:00:01.000Z',
        gitBranch: 'main',
        cwd: '/repo',
        message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 't2', content: 'x' }] },
        toolUseResult: { interrupted: false, stdout: '', stderr: '', isImage: false, noOutputExpected: false },
      },
    ];
    const record = deriveSessionRecord(rows, baseContext);
    expect(record.tool_calls_interrupted).toBe(1);
    expect(record.turns).toBe(0); // both remain echoes, no real turn
  });

  it('populates files_written from Edit/Write/MultiEdit, distinct from files_read', () => {
    const rows = [
      assistantRow({
        requestId: 'r1',
        model: 'claude-sonnet-5',
        output: 10,
        gitBranch: 'main',
        content: [
          { type: 'tool_use', name: 'Read', input: { file_path: 'a.ts' } },
          { type: 'tool_use', name: 'Write', input: { file_path: 'b.ts' } },
          { type: 'tool_use', name: 'Edit', input: { file_path: 'b.ts' } },
        ],
      }),
    ];
    const record = deriveSessionRecord(rows, baseContext);
    expect(record.files_read).toEqual(['a.ts']);
    expect(record.files_written).toEqual(['b.ts']);
    expect(record.tool_calls).toEqual({ Read: 1, Write: 1, Edit: 1 });
  });

  it('a transcript with no dated event falls back to nowIso instead of throwing', () => {
    const record = deriveSessionRecord([{ type: 'agent-setting', agentSetting: 'tech-lead' }], baseContext);
    expect(record.started_at).toBe(baseContext.nowIso);
    expect(record.updated_at).toBe(baseContext.nowIso);
    expect(record.turns).toBe(0);
  });
});

describe('isPushDue — when each event actually pushes', () => {
  it('SessionStart\'s sweep does NOT re-push a record already pushed and unchanged since then', () => {
    // `updated_at` no more recent than `pushed_at`: no new write to
    // consolidate since the last successful push. If the sweep pushed
    // anyway, remote traffic would grow with the entire local history on
    // every startup instead of with the current session's work.
    const due = isPushDue(
      { updated_at: '2026-08-25T09:00:00.000Z', pushed_at: '2026-08-25T09:05:00.000Z' },
      null,
      'session_start_sweep',
    );
    expect(due).toBe(false);
  });

  it('SessionStart\'s sweep pushes a record more recent than its pushed_at, or never pushed', () => {
    const staleSincePush = isPushDue(
      { updated_at: '2026-08-25T09:10:00.000Z', pushed_at: '2026-08-25T09:05:00.000Z' },
      null,
      'session_start_sweep',
    );
    expect(staleSincePush).toBe(true);

    const neverPushed = isPushDue(
      { updated_at: '2026-08-25T09:10:00.000Z', pushed_at: null },
      null,
      'session_start_sweep',
    );
    expect(neverPushed).toBe(true);
  });

  it('SessionEnd always pushes, even a record identical to a just-succeeded push', () => {
    const due = isPushDue(
      { updated_at: '2026-08-25T09:00:00.000Z', pushed_at: '2026-08-25T09:00:00.000Z' },
      null,
      'session_end',
    );
    expect(due).toBe(true);
  });

  it('Stop respects the 5-minute threshold since the last successful push OF THIS session', () => {
    const tooSoon = isPushDue(
      { updated_at: '2026-08-25T09:04:00.000Z', pushed_at: null },
      { pushed_at: '2026-08-25T09:00:00.000Z' },
      'stop',
    );
    expect(tooSoon).toBe(false);

    const dueByThreshold = isPushDue(
      { updated_at: '2026-08-25T09:05:00.000Z', pushed_at: null },
      { pushed_at: '2026-08-25T09:00:00.000Z' },
      'stop',
    );
    expect(dueByThreshold).toBe(true);
  });
});
